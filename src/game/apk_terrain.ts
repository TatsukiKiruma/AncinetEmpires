const APPROXIMATE_SKIRMISH_APK_TERRAIN_IDS = new Set([30, 31, 33, 80, 81, 82, 83]);

function getSkirmishMappingEvidence(
    apkTerrainId: number,
    projectTerrainId: TerrainId | null,
    confidence: ApkTerrainMappingConfidence
): string[] {
    if (confidence === 'unmapped' || projectTerrainId === null) return [];
    if (confidence === 'confirmed') {
        if (apkTerrainId === 72) {
            return ['data_bin_values', 'language_table_bridge_is_water', 'texture_atlas'];
        }
        return ['data_bin_values', 'language_table_building_description', 'texture_atlas'];
    }
    if (confidence === 'approximate') {
        if (apkTerrainId === 30) {
            return ['data_bin_values', 'texture_atlas', 'low_confidence_camp_semantics'];
        }
        if (apkTerrainId === 31 || apkTerrainId === 80) {
            return ['data_bin_values', 'texture_atlas', 'language_table_temple_description', 'low_confidence_temple_semantics'];
        }
        if (apkTerrainId === 81 || apkTerrainId === 82) {
            return ['data_bin_values', 'texture_atlas', 'low_confidence_water_obstacle_semantics'];
        }
        if (apkTerrainId === 83) {
            return ['data_bin_values', 'texture_atlas', 'language_table_temple_description', 'low_confidence_water_temple_semantics'];
        }
        return ['data_bin_values', 'texture_atlas', 'low_confidence_building_semantics'];
    }
    return ['data_bin_values', 'texture_atlas', 'skirmish_map_context'];
}

export function getSkirmishApkTerrainMappingInfo(apkTerrainId: number): ApkTerrainMappingInfo {
    const projectTerrainId = mapSkirmishApkTerrainId(apkTerrainId);
    const confidence: ApkTerrainMappingConfidence = projectTerrainId === null
        ? 'unmapped'
        : mapKnownApkTerrainId(apkTerrainId) !== null
            ? 'confirmed'
            : APPROXIMATE_SKIRMISH_APK_TERRAIN_IDS.has(apkTerrainId)
                ? 'approximate'
                : 'atlas';

    return {
        apkTerrainId,
        projectTerrainId,
        confidence,
        evidence: getSkirmishMappingEvidence(apkTerrainId, projectTerrainId, confidence)
    };
}

export function getApkTerrainConfig(apkTerrainId: number): ApkTerrainConfig | null {
    return APK_TERRAIN_BY_ID.get(apkTerrainId) ?? null;
}

export function mapKnownApkTerrainId(apkTerrainId: number): TerrainId | null {
    return HIGH_CONFIDENCE_APK_TERRAIN_TO_PROJECT[apkTerrainId] ?? null;
}

export function mapSkirmishApkTerrainId(apkTerrainId: number): TerrainId | null {
    return SKIRMISH_APK_TERRAIN_TO_PROJECT[apkTerrainId] ?? null;
}

export function getKnownApkTerrainIdsForProject(terrainId: TerrainId): number[] {
    return Object.entries(HIGH_CONFIDENCE_APK_TERRAIN_TO_PROJECT)
        .filter(([, projectTerrainId]) => projectTerrainId === terrainId)
        .map(([apkTerrainId]) => Number(apkTerrainId))
        .sort((a, b) => a - b);
}

export function getSkirmishApkTerrainIdsForProject(terrainId: TerrainId): number[] {
    return Object.entries(SKIRMISH_APK_TERRAIN_TO_PROJECT)
        .filter(([, projectTerrainId]) => projectTerrainId === terrainId)
        .map(([apkTerrainId]) => Number(apkTerrainId))
        .sort((a, b) => a - b);
}

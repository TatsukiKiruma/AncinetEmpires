import { createDemoState } from '../../src/game/demo_map';
import { GameEngine } from '../../src/game/engine';
import { movingThreat,movingThreatExhaustive,nextOpponent } from './threat';
import { save } from './io';
import {extractFeatures as completeFeatures} from './complete_tactics';
const state=createDemoState();
state.map.tiles=state.map.tiles.map(row=>row.map(()=>({terrainId:6,ownerId:null})));
const commander={...state.units[0],hasActed:true,hasMoved:true};
const actor={...state.units[2],unitClass:'archer' as const,pos:{x:3,y:2},hp:40,status:{type:'poisoned' as const,remainingTurns:3}};
const ghost={...state.units[3],unitClass:'ghost' as const,pos:{x:4,y:2},hp:10};
const elf={...state.units[3],id:'elf_probe',unitClass:'elf' as const,pos:{x:4,y:3},hp:5};
state.units=[commander,actor,ghost,elf];state.players.forEach(p=>p.gold=0);
const engine=new GameEngine(state);engine.step({type:'wait',unitId:actor.id});
const reply=nextOpponent(engine,0);const target=reply.branch.getState().units.find(u=>u.id===actor.id)!;
const fast=movingThreat(reply.branch,[target]).get(target.id),full=movingThreatExhaustive(reply.branch,[target]).get(target.id);
const complete=completeFeatures(new GameEngine(state),[{type:'wait',unitId:actor.id}]);
if(complete.extra[0][4]*128!==full!.damage)throw Error('v3组合光环风险仍不准确');
save('aura-guard-probe.json',{passed:true,state,action:{type:'wait',unitId:actor.id},fast,full,complete:complete.extra[0][4]*128});
console.log(JSON.stringify({passed:true,fast,full,complete:complete.extra[0][4]*128}));

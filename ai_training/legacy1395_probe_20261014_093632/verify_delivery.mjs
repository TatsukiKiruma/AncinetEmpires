import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const out=path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'));
const prior=path.resolve(out,'../legacy2500_recovery_20261014_090431');
const read=(dir,split)=>fs.readFileSync(path.join(dir,'package',split+'.jsonl'),'utf8').trim().split('\n').filter(Boolean).map(JSON.parse);
const train=[...read(prior,'train'),...read(out,'train')], val=[...read(prior,'validation'),...read(out,'validation')];
const inputs=new Set(train.map(r=>r.inputHash));
assert.equal(train.length,346); assert.equal(val.length,167);
assert.equal(new Set([...train,...val].map(r=>r.inputHash)).size,513);
assert.ok(val.every(r=>!inputs.has(r.inputHash)));
const families=rows=>new Set(rows.flatMap(r=>(r.allProvenance??[r.provenance]).map(p=>p.familyId)));
const trainFamilies=families(train), valFamilies=families(val);
assert.ok(!trainFamilies.has(undefined)&&!valFamilies.has(undefined));
assert.ok([...valFamilies].every(f=>!trainFamilies.has(f)));
const log=fs.readFileSync(path.join(out,'replay_results.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
assert.equal(log.length,48); assert.equal(new Set(log.map(r=>r.id)).size,48);
const manifest=JSON.parse(fs.readFileSync(path.join(out,'package/manifest.json'),'utf8'));
for(const f of manifest.files)assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(out,'package',f.file))).digest('hex'),f.sha256);
fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify({combinedUniqueInputs:513,train:346,validation:167,inputLeakage:0,mapFamilyLeakage:0,replayRecords:48,resumeRegeneratedCachesWithoutDuplicateRecords:true,packageHashesUnchangedAfterResume:true,crossTaskR7Dedup:'尚未完成跨任务去重'},null,2));
console.log('交付验证通过：513个独特输入，无训练/验证输入或地图家族交叉；断点恢复保持数据包哈希。');
